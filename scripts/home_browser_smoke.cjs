const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
(async()=>{
 const out=path.resolve('output/test-reports',new Date().toISOString().replace(/[:.]/g,'-')+'_home-browser');fs.mkdirSync(out,{recursive:true});
 const base=process.env.APPLYGUARD_TEST_URL||'http://127.0.0.1:5173';
 const browser=await chromium.launch({channel:'msedge',headless:true,args:['--no-proxy-server']});
 const page=await browser.newPage({viewport:{width:1440,height:1100}}),checks=[],errors=[],consoleMessages=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',message=>{if(['warning','error'].includes(message.type()))consoleMessages.push(message.text())});
 try {
  await page.addInitScript(()=>sessionStorage.setItem('applyguard.guide.collapsed','true'));
  await page.goto(base+'/');
  await page.getByRole('heading',{name:'24 秒操作介绍',exact:true}).waitFor();
  const importCard=page.getByRole('region',{name:'上传 PDF',exact:true});
  const reelCard=page.getByRole('region',{name:'24 秒操作介绍',exact:true});
  const importLink=page.getByRole('button',{name:'选择简历',exact:true});
  assert.equal(await importCard.evaluate(el=>el.offsetTop),await reelCard.evaluate(el=>el.offsetTop));
  for(const card of [importCard,reelCard]) {
   const style=await card.evaluate(el=>{
    const computed=getComputedStyle(el);
    return [computed.paddingTop,computed.borderTopWidth,computed.borderRadius,computed.backgroundColor,computed.backgroundImage];
   });
   assert.deepEqual(style.slice(0,4),['32px','1px','24px','rgb(250, 248, 245)']);
   assert.match(style[4],/^linear-gradient/);
  }
  assert.equal(await importLink.evaluate(el=>getComputedStyle(el).borderRadius),'999px');
  const heading=page.getByRole('heading',{name:'简历导入',level:2,exact:true});
  const type=await heading.evaluate(el=>[parseFloat(getComputedStyle(el).fontSize),parseInt(getComputedStyle(el).fontWeight)]);
  assert.ok(type[0]===48 && type[1]>=700);
  assert.equal(await page.locator('.home-intro-copy p').evaluate(el=>getComputedStyle(el).fontSize),'17px');
  assert.equal(await importLink.evaluate(el=>getComputedStyle(el).fontSize),'16px');
  await importLink.hover();
  await page.waitForFunction(()=>{
   const button=document.querySelector('.home-actions button');
   return new DOMMatrix(getComputedStyle(button).transform).f===-2;
  });
  await page.mouse.down();
  await page.waitForFunction(()=>{
   const style=getComputedStyle(document.querySelector('.home-actions button'));
   const matrix=new DOMMatrix(style.transform);
   return matrix.a===.98 && style.boxShadow.includes('inset');
  });
  await page.mouse.move(1,1);
  await page.mouse.up();
  const mode=page.getByLabel('识别方式');
  await mode.focus();
  assert.equal(await mode.evaluate(el=>getComputedStyle(el).outlineColor),'rgb(74, 111, 165)');
  await mode.blur();
  checks.push('watercolor-cards-on-warm-paper','title-and-description-hierarchy','capsule-hover-and-press','visible-input-focus');
  const stage=page.locator('.homepage-reel .reel-stage');
  await stage.waitFor();
  await page.locator('.homepage-reel .project-player[data-playing=true]').waitFor({timeout:30000});
  await stage.locator('[data-reel-scene="experience"]').waitFor({timeout:10000});
  assert.equal(await page.locator('.homepage-reel audio').evaluate(el=>el.paused),true);
  checks.push('homepage-reel-expanded-despite-old-preference','watercolor-stage-advances','default-muted');
  await page.getByRole('button',{name:'暂停新手引导',exact:true}).click();
  await page.locator('.homepage-reel .project-player[data-playing=false]').waitFor();
  await page.getByRole('button',{name:'回到开头',exact:true}).click();
  await stage.locator('[data-reel-scene="open"]').waitFor();
  const chapters=page.locator('.homepage-reel .reel-chapters button');
  for(const [index,id] of ['experience','evidence','job','review'].entries()) {
   await chapters.nth(index).click();
   assert.equal(await chapters.nth(index).getAttribute('aria-pressed'),'true');
   assert.equal(await stage.locator(`[data-reel-scene="${id}"] li`).count(),3);
   if(id==='evidence') await stage.screenshot({path:path.join(out,'watercolor-reel-evidence.png')});
  }
  await page.locator('.homepage-reel input[type=range]').press('End');
  await stage.locator('[data-reel-scene="close"]').waitFor();
  await page.getByRole('button',{name:'回到开头',exact:true}).click();
  checks.push('pause-restart-four-chapters-and-scrub-to-outro');
  await page.screenshot({path:path.join(out,'homepage-desktop.png'),fullPage:true});
  await page.locator('.homepage-reel').scrollIntoViewIfNeeded();
  await stage.locator('[data-reel-scene="open"]').waitFor();
  await page.locator('.home-intro').screenshot({path:path.join(out,'homepage-hero.png')});
  const chooserPromise=page.waitForEvent('filechooser');
  await importLink.click();
  const chooser=await chooserPromise;
  await chooser.setFiles([]);
  assert.ok(await page.getByLabel('选择 PDF 简历').isEnabled());checks.push('import-cta-retains-existing-form');
  await page.getByRole('link',{name:'查看完整操作说明',exact:false}).click();
  await page.getByRole('heading',{name:'准备一份有依据的申请',exact:true}).waitFor();
  await page.locator('.help-animation > summary').click();
  await page.getByRole('button',{name:'展开引导',exact:true}).click();
  await page.locator('.help-animation [data-reel-scene="open"]').waitFor();
  checks.push('help-navigation-and-shared-watercolor-reel');
  await page.goto(base+'/');
  await page.setViewportSize({width:1280,height:900});
  await page.locator('.homepage-reel .reel-stage').scrollIntoViewIfNeeded();
  await stage.waitFor();
  assert.ok(!await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth));
  await page.screenshot({path:path.join(out,'homepage-1280.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.locator('.homepage-reel .reel-stage').scrollIntoViewIfNeeded();
  await stage.waitFor();
  assert.ok(!await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth));
  assert.ok((await importCard.boundingBox()).y < (await reelCard.boundingBox()).y);
  assert.equal(await importCard.evaluate(el=>getComputedStyle(el).paddingTop),'24px');
  await page.screenshot({path:path.join(out,'homepage-mobile.png'),fullPage:true});
  await page.setViewportSize({width:320,height:760});
  await chapters.nth(3).click();
  assert.ok(!await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth));
  const stageBottom=await stage.evaluate(el=>el.getBoundingClientRect().bottom);
  assert.ok(await stage.locator('.watercolor-reel-checklist').evaluate(el=>el.getBoundingClientRect().bottom)<=stageBottom);
  checks.push('1280-and-mobile-no-overflow','short-screen-watercolor-frame-fits');
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.ok(await page.getByRole('button',{name:'系统已开启减少动态效果',exact:true}).isDisabled());
  await page.locator('.homepage-reel .project-player[data-playing=false]').waitFor();
  await importLink.hover();
  assert.equal(await importLink.evaluate(el=>getComputedStyle(el).transform),'none');
  assert.equal(await stage.locator('.watercolor-reel-sheet').evaluate(el=>getComputedStyle(el).getPropertyValue('--wash-reveal').trim()),'1');
  checks.push('respects-reduced-motion');
  await page.setViewportSize({width:1440,height:1100});
  await page.emulateMedia({colorScheme:'dark'});
  await page.goto(base+'/history');
  await page.getByRole('heading',{name:'简历生成',exact:true,level:2}).waitFor();
  assert.equal(await page.locator('meta[name="color-scheme"]').getAttribute('content'),'only light');
  assert.deepEqual(await page.evaluate(()=>getComputedStyle(document.documentElement).colorScheme.split(/\s+/).sort()),['light','only']);
  const paperCorner={x:0,y:0,width:12,height:12};
  const before=await page.screenshot({clip:paperCorner});
  const cdp=await page.context().newCDPSession(page);
  await cdp.send('Emulation.setAutoDarkModeOverride',{enabled:true});
  assert.deepEqual(await page.screenshot({clip:paperCorner}),before);
  await page.screenshot({path:path.join(out,'history-browser-auto-dark.png')});
  checks.push('history-retains-paper-color-with-browser-auto-dark');
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(out,'report.json'),JSON.stringify({date:new Date().toISOString(),base,status:'PASS',checks,errors,consoleMessages},null,2));
  console.log('PASS '+out);
 }catch(e){
  await page.screenshot({path:path.join(out,'failure.png'),fullPage:true});
  fs.writeFileSync(path.join(out,'report.json'),JSON.stringify({date:new Date().toISOString(),status:'FAIL',checks,error:String(e),errors,consoleMessages},null,2));
  console.error('FAIL '+out);throw e;
 }finally{await browser.close()}
})().catch(e=>{console.error(e.message);process.exitCode=1});
